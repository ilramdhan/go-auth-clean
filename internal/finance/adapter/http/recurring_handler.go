// updateRecurringRule godoc
//
//	@Summary		Update recurring rule
//	@Description	Partial update. Changing the schedule recomputes next_run_date (never before the last run). end_date "" removes the end date.
//	@Tags			recurring-rules
//	@Accept			json
//	@Produce		json
//	@Security		BearerAuth
//	@Param			id			path		string						true	"Rule ID"	format(uuid)
//	@Param			If-Match	header		string						false	"Expected version"
//	@Param			body		body		UpdateRecurringRuleRequest	true	"Fields to change"
//	@Success		200			{object}	RecurringRuleEnvelope
//	@Failure		401			{object}	httpx.ErrorResponse	"UNAUTHENTICATED"
//	@Failure		404			{object}	httpx.ErrorResponse	"RECURRING_RULE_NOT_FOUND / ACCOUNT_NOT_FOUND / CATEGORY_NOT_FOUND"
//	@Failure		409			{object}	httpx.ErrorResponse	"VERSION_CONFLICT"
//	@Failure		422			{object}	httpx.ErrorResponse	"VALIDATION_FAILED / RULE_ENDED / INVALID_FREQUENCY"
//	@Router			/recurring-rules/{id} [patch]
func (h *Handler) updateRecurringRule(w http.ResponseWriter, r *http.Request) {
	h.ruleAction(w, r, func(uid, id uuid.UUID) (*domain.RecurringRule, error) {
		ver, err := ifMatch(r)
		if err != nil {
			return nil, err
		}
		req, err := decodeAndValidate[UpdateRecurringRuleRequest](h, w, r)
		if err != nil {
			return nil, err
		}
		in := app.UpdateRecurringInput{UserID: uid, ID: id, ExpectedVersion: ver, Type: req.Type, Amount: req.Amount,
			Note: req.Note, Frequency: req.Frequency, Interval: req.Interval, Count: req.Count}
		if in.AccountID, err = parseUUIDPtr("account_id", req.AccountID); err != nil {
			return nil, err
		}
		if in.CategoryID, err = parseUUIDPtr("category_id", req.CategoryID); err != nil {
			return nil, err
		}
		if in.StartDate, err = parseDatePtr("start_date", req.StartDate); err != nil {
			return nil, err
		}
		if req.EndDate != nil {
			var end *time.Time
			if *req.EndDate != "" {
				if end, err = parseDatePtr("end_date", req.EndDate); err != nil {
					return nil, err
				}
			}
			in.EndDate = &end
		}
		return h.svc.UpdateRecurringRule(r.Context(), in)
	})
}

