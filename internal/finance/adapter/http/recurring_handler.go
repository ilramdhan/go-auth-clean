// listRecurringRules godoc
//
//	@Summary		List recurring rules
//	@Description	Newest first (created_at, id DESC), cursor paginated.
//	@Tags			recurring-rules
//	@Produce		json
//	@Security		BearerAuth
//	@Param			limit	query		int		false	"Page size (1-100, default 20)"
//	@Param			cursor	query		string	false	"Opaque cursor from meta.next_cursor"
//	@Success		200		{object}	RecurringRuleListEnvelope
//	@Failure		400		{object}	httpx.ErrorResponse	"INVALID_PARAMETER / INVALID_CURSOR"
//	@Failure		401		{object}	httpx.ErrorResponse	"UNAUTHENTICATED"
//	@Router			/recurring-rules [get]
func (h *Handler) listRecurringRules(w http.ResponseWriter, r *http.Request) {
	uid, ok := userID(w, r)
	if !ok {
		return
	}
	q := r.URL.Query()
	limit, err := pagination.ParseLimit(q.Get("limit"))
	if err != nil {
		httpx.WriteError(w, r, invalidParam("limit", err.Error()))
		return
	}
	filter := pagination.FilterHash("recurring-rules")
	cur, err := pagination.Decode(q.Get("cursor"), filter)
	if err != nil {
		httpx.WriteError(w, r, mapError(err))
		return
	}
	var after *domain.PageKey
	if cur != nil {
		after = &domain.PageKey{Date: cur.Time, ID: cur.ID}
	}
	rules, err := h.svc.ListRecurringRules(r.Context(), uid, limit, after)
	if err != nil {
		httpx.WriteError(w, r, mapError(err))
		return
	}
	page, meta := pagination.Page(rules, limit, filter, func(x *domain.RecurringRule) (time.Time, uuid.UUID) {
		return x.CreatedAt(), x.ID()
	})
	out := make([]RecurringRuleResponse, 0, len(page))
	for _, x := range page {
		out = append(out, toRecurringRuleResponse(x))
	}
	httpx.List(w, out, meta)
}

// createRecurringRule godoc
//
//	@Summary		Create recurring rule
//	@Description	Template transaction generated by a background worker on each occurrence (idempotent per rule + date). Monthly/yearly rules anchor on the start_date day, clamped to month end. Use end_date or count (not both). Requires Idempotency-Key.
//	@Tags			recurring-rules
//	@Accept			json
//	@Produce		json
//	@Security		BearerAuth
//	@Param			Idempotency-Key	header		string						true	"Unique key per logical request (8-128 chars)"
//	@Param			body			body		CreateRecurringRuleRequest	true	"Rule"
//	@Success		201				{object}	RecurringRuleEnvelope
//	@Failure		400				{object}	httpx.ErrorResponse	"INVALID_JSON / IDEMPOTENCY_KEY_REQUIRED"
//	@Failure		401				{object}	httpx.ErrorResponse	"UNAUTHENTICATED"
//	@Failure		404				{object}	httpx.ErrorResponse	"ACCOUNT_NOT_FOUND / CATEGORY_NOT_FOUND"
//	@Failure		409				{object}	httpx.ErrorResponse	"IDEMPOTENCY_IN_PROGRESS"
//	@Failure		422				{object}	httpx.ErrorResponse	"VALIDATION_FAILED / INVALID_FREQUENCY / CATEGORY_TYPE_MISMATCH / ACCOUNT_ARCHIVED"
//	@Router			/recurring-rules [post]
func (h *Handler) createRecurringRule(w http.ResponseWriter, r *http.Request) {
	uid, ok := userID(w, r)
	if !ok {
		return
	}
	req, err := decodeAndValidate[CreateRecurringRuleRequest](h, w, r)
	if err != nil {
		httpx.WriteError(w, r, mapError(err))
		return
	}
	in, err := createRecurringInput(uid, req)
	if err != nil {
		httpx.WriteError(w, r, err)
		return
	}
	h.idempotent(w, r, uid, "/api/v1/recurring-rules", req, func(ctx context.Context) (int, any, error) {
		x, err := h.svc.CreateRecurringRule(ctx, in)
		if err != nil {
			return 0, nil, err
		}
		return http.StatusCreated, toRecurringRuleResponse(x), nil
	})
}

func createRecurringInput(uid uuid.UUID, req CreateRecurringRuleRequest) (app.CreateRecurringInput, error) {
	in := app.CreateRecurringInput{UserID: uid, Type: req.Type, Amount: req.Amount, Note: req.Note,
		Frequency: req.Frequency, Interval: req.Interval, Count: req.Count}
	var err error
	if in.AccountID, err = uuid.Parse(req.AccountID); err != nil {
		return in, invalidParam("account_id", "harus UUID")
	}
	if in.CategoryID, err = uuid.Parse(req.CategoryID); err != nil {
		return in, invalidParam("category_id", "harus UUID")
	}
	if in.StartDate, err = parseDate("start_date", req.StartDate); err != nil {
		return in, err
	}
	if req.EndDate != "" {
		if in.EndDate, err = parseDatePtr("end_date", &req.EndDate); err != nil {
			return in, err
		}
	}
	return in, nil
}

