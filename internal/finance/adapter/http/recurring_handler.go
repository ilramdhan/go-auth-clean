// pauseRecurringRule godoc
//
//	@Summary	Pause recurring rule
//	@Tags		recurring-rules
//	@Accept		json
//	@Produce	json
//	@Security	BearerAuth
//	@Param		id		path		string						true	"Rule ID"	format(uuid)
//	@Param		body	body		PauseRecurringRuleRequest	false	"Optional reason"
//	@Success	200		{object}	RecurringRuleEnvelope
//	@Failure	401		{object}	httpx.ErrorResponse	"UNAUTHENTICATED"
//	@Failure	404		{object}	httpx.ErrorResponse	"RECURRING_RULE_NOT_FOUND"
//	@Failure	422		{object}	httpx.ErrorResponse	"RULE_ENDED"
//	@Router		/recurring-rules/{id}/pause [post]
func (h *Handler) pauseRecurringRule(w http.ResponseWriter, r *http.Request) {
	h.ruleAction(w, r, func(uid, id uuid.UUID) (*domain.RecurringRule, error) {
		var req PauseRecurringRuleRequest
		if r.ContentLength != 0 {
			var err error
			if req, err = decodeAndValidate[PauseRecurringRuleRequest](h, w, r); err != nil {
				return nil, err
			}
		}
		return h.svc.PauseRecurringRule(r.Context(), uid, id, req.Reason)
	})
}

// resumeRecurringRule godoc
//
