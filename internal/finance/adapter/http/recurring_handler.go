func (h *Handler) ruleAction(w http.ResponseWriter, r *http.Request, fn func(uid, id uuid.UUID) (*domain.RecurringRule, error)) {
	uid, ok := userID(w, r)
	if !ok {
		return
	}
	id, err := pathID(r, domain.ErrRecurringNotFound)
	if err == nil {
		var x *domain.RecurringRule
		if x, err = fn(uid, id); err == nil {
			setETag(w, x.Version())
			httpx.Data(w, http.StatusOK, toRecurringRuleResponse(x))
			return
		}
	}
	httpx.WriteError(w, r, mapError(err))
}
